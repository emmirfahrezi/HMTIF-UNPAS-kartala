## Bidang Organisasi
- BPH (Badan Pengurus Harian): Koordinasi keseluruhan kepengurusan
- KASTRAD (Kajian Aksi Strategi Advokasi): Kajian isu dan advokasi mahasiswa
- KOMINFO (Komunikasi dan Informasi): Media dan publikasi organisasi
- KESKRAF (Kesekretariatan Ekonomi Kreatif): Niaga dan produk himpunan
- PSDM (Pengembangan Sumber Daya Mahasiswa): Pelatihan dan pengembangan anggota
- PMB (Pemberdayaan Minat Bakat): Olahraga, seni, dan kompetisi


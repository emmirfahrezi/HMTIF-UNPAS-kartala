# HMTIF-UNPAS

> Portal resmi Himpunan Mahasiswa Teknik Informatika Universitas Pasundan, Kabinet Kartala — wadah aspirasi, informasi kegiatan, dan pengembangan potensi mahasiswa Teknik Informatika UNPAS Bandung.

## Tentang
HMTIF-UNPAS adalah organisasi kemahasiswaan program studi Teknik Informatika Universitas Pasundan Bandung. Kabinet aktif: Kartala. Bergerak di bidang pengembangan SDM, advokasi mahasiswa, komunikasi & informasi, kreativitas, serta pemberdayaan minat bakat.

